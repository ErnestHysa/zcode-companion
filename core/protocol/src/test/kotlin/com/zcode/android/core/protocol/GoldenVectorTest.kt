/**
 * Golden fixtures generated by executing the reference TypeScript implementation
 * (packages/rpc serialization/protocol + shared wire-binary) — the byte-identity proof
 * demanded by S43.2-1.2. Fixture metadata carries source, version, capture date and
 * sanitization status per S41.3.
 */
class GoldenVectorTest {

    private val vectors: JsonObject by lazy {
        val file = sequenceOf(File("."), File(".."), File("../.."))
            .map { it.resolve("fixtures/protocol/golden-vectors.json") }
            .firstOrNull { it.isFile }
            ?: error("golden-vectors.json not found")
        Json.parseToJsonElement(file.readText()).jsonObject
    }

    private fun cases(kind: String): List<String> =
        (vectors["cases"]!!.jsonArray)
            .map { it.jsonObject }
            .filter { it["kind"]!!.jsonPrimitive.content == kind }
            .map { it["name"]!!.jsonPrimitive.content }

    private fun expectedOf(name: String): String =
        (vectors["cases"]!!.jsonArray)
            .map { it.jsonObject }
            .first { it["name"]!!.jsonPrimitive.content == name }["expected"]!!.jsonPrimitive.content

    private fun hex(bytes: ByteArray): String = bytes.joinToString("") { "%02x".format(it) }
    private fun unhex(s: String): ByteArray = ByteArray(s.length / 2) {
        ((Character.digit(s[it * 2], 16) shl 4) + Character.digit(s[it * 2 + 1], 16)).toByte()
    }

    // ---------------------------------------------------------- serialize cases

    private fun buildValue(name: String): RpcValue = when (name) {
        "undefined" -> RpcValue.Undefined
        "string-ascii" -> RpcValue.Str("hello zcode")
        "string-unicode" -> RpcValue.Str("\u4f60\u597d\uff0cZCode \u2705")
        "string-escapes" -> RpcValue.Str("quote\" back\\slash\nnnewline\ttab\u0000ctrl\u0001")
        "int-0" -> RpcValue.Int(0)
        "int-1" -> RpcValue.Int(1)
        "int-127" -> RpcValue.Int(127)
        "int-128" -> RpcValue.Int(128)
        "int-16383" -> RpcValue.Int(16383)
        "int-16384" -> RpcValue.Int(16384)
        "int-max" -> RpcValue.Int(2147483647)
        "int-negative" -> RpcValue.Int(-1)
        "int-min" -> RpcValue.Int(-2147483648)
        "float" -> RpcValue.Obj(JsonUnquotedLiteral("1.5"))
        "bool-true" -> RpcValue.Obj(JsonPrimitive(true))
        "bool-false" -> RpcValue.Obj(JsonPrimitive(false))
        "null" -> RpcValue.Obj(JsonNull)
        "empty-array" -> RpcValue.Arr(emptyList())
        "array-mixed" -> RpcValue.Arr(
            listOf(
                RpcValue.Int(1), RpcValue.Str("two"), RpcValue.Obj(JsonPrimitive(true)),
                RpcValue.Obj(JsonNull),
                RpcValue.Obj(buildJsonObject { put("three", JsonPrimitive(3)) }),
            )
        )
        "empty-object" -> RpcValue.Obj(buildJsonObject { })
        "object-simple" -> RpcValue.Obj(
            buildJsonObject {
                put("b", JsonPrimitive(true))
                put("a", JsonPrimitive(1))
                put("c", JsonPrimitive("x"))
            }
        )
        "object-nested" -> RpcValue.Obj(
            buildJsonObject {
                put(
                    "outer",
                    buildJsonObject {
                        put(
                            "inner",
                            buildJsonArray {
                                add(JsonPrimitive(1))
                                add(JsonPrimitive(2))
                                add(buildJsonObject { put("deep", JsonPrimitive("v")) })
                            }
                        )
                    }
                )
                put("flag", JsonPrimitive(false))
            }
        )
        "object-unicode-key" -> RpcValue.Obj(
            buildJsonObject {
                put("\u952e", JsonPrimitive("\u503c"))
                put("id", JsonPrimitive(42))
            }
        )
        "uint8array-top" -> RpcValue.Buf(byteArrayOf(1, 2, 3, 0xFA.toByte(), 0xFF.toByte()))
        "vsbuffer-top" -> RpcValue.VsBuf("vsbuffer payload".encodeToByteArray())
        "object-nested-uint8array" -> RpcValue.Obj(
            buildJsonObject {
                put("blob", RpcJson.nestedBytesMarker("AP+A"))
                put("name", JsonPrimitive("x"))
            }
        )
        else -> error("no builder for $name")
    }

    @Test
    fun `serialize golden vectors are byte-identical`() {
        for (name in cases("serialize")) {
            val built = buildValue(name)
            assertEquals(expectedOf(name), hex(RpcSerialization.encode(built)), "serialize case: $name")
        }
    }

    @Test
    fun `reference self-roundtrip vectors re-decode and re-encode identically`() {
        // The generator recorded reference(serialize(deserialize(serialize(x)))) for each case.
        for (name in cases("deserialize-check")) {
            val base = name.removeSuffix("::reparse")
            val bytes = unhex(expectedOf(base))
            val decoded = RpcSerialization.decode(bytes)
            assertEquals(expectedOf(name), hex(RpcSerialization.encode(decoded)), "reparse case: $name")
        }
    }

    // ---------------------------------------------------------- framing

    @Test
    fun `socket frame golden vectors are byte-identical`() {
        val builders: Map<String, SocketFrame.ProtocolMessage> = mapOf(
            "regular-empty" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Regular, 0, 0, ByteArray(0)),
            "regular-payload" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Regular, 7, 0, byteArrayOf(10, 20, 30)),
            "keepalive" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.KeepAlive, 0, 12, ByteArray(0)),
            "ack" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Ack, 0, 42, ByteArray(0)),
            "disconnect" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Disconnect, 0, 99, ByteArray(0)),
            // JS writeUInt32BE(4294967295) -> 0xffffffff -> Kotlin Int -1
            "large-id" to SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Regular, -1, -1, byteArrayOf(1)),
        )
        for (name in cases("frame")) {
            val msg = builders[name] ?: error("no frame builder for $name")
            assertEquals(expectedOf(name), hex(SocketFrame.writeMessage(msg)), "frame case: $name")
        }
    }

    @Test
    fun `chunk stream drain vectors match reference reassembly`() {
        val payload = "chunked-message-body".encodeToByteArray()
        val source = SocketFrame.writeMessage(
            SocketFrame.ProtocolMessage(SocketFrame.ProtocolMessageType.Regular, 5, 3, payload)
        )
        val plans = listOf(
            listOf(5, source.size),
            listOf(0, 13, source.size),
            listOf(13, 14, source.size),
            listOf(source.size),
        )
        for (name in cases("chunk-drain")) {
            val idx = name.removePrefix("chunk-split-").toInt()
            val cs = ChunkStream()
            var off = 0
            for (b in plans[idx]) {
                if (b > off) {
                    cs.acceptChunk(source.copyOfRange(off, b))
                    off = b
                }
            }
            val got = ArrayList<String>()
            while (cs.byteLength >= SocketFrame.HEADER_SIZE) {
                val header = cs.peek(SocketFrame.HEADER_SIZE)!!
                val (_, _, length) = SocketFrame.parseHeader(header)
                if (cs.byteLength < SocketFrame.HEADER_SIZE + length) break
                cs.skip(SocketFrame.HEADER_SIZE)
                got.add(hex(cs.read(length)!!))
            }
            val expected = (vectors["cases"]!!.jsonArray
                .map { it.jsonObject }
                .first { it["name"]!!.jsonPrimitive.content == name }["expected"] as JsonArray)
                .map { it.jsonPrimitive.content }
            assertEquals(expected, got, "chunk case: $name")
        }
    }

    // ---------------------------------------------------------- crc32

    @Test
    fun `crc32 wire vectors are identical`() {
        val inputs: Map<String, ByteArray> = mapOf(
            "empty" to ByteArray(0),
            "one-zero" to byteArrayOf(0),
            "123456789" to "123456789".encodeToByteArray(),
            "binary" to byteArrayOf(0xDE.toByte(), 0xAD.toByte(), 0xBE.toByte(), 0xEF.toByte(), 0, 0xFF.toByte()),
            "hello" to "hello zcode crc".encodeToByteArray(),
        )
        for (name in cases("crc32")) {
            assertEquals(expectedOf(name), Crc32Wire.checksum(inputs[name]!!), "crc case: $name")
        }
    }

    // ---------------------------------------------------------- channel shapes

    @Test
    fun `channel wire shapes are byte-identical`() {
        assertEquals(
            expectedOf("request-promise"),
            hex(
                ChannelWire.encodeRequest(
                    ChannelWire.RequestType.Promise, 1, "zcode-agent", "helloConversationV4",
                    RpcValue.Obj(buildJsonObject {
                        put("kind", JsonPrimitive("clientHello"))
                        put("protocolVersion", JsonPrimitive(3))
                    })
                )
            )
        )
        assertEquals(
            expectedOf("request-eventlisten"),
            hex(
                ChannelWire.encodeRequest(
                    ChannelWire.RequestType.EventListen, 2, "zcode-agent", "onDynamicSessionEvent",
                    RpcValue.Obj(buildJsonObject { put("sessionId", JsonPrimitive("sess_x")) })
                )
            )
        )
        assertEquals(expectedOf("cancel"), hex(ChannelWire.encodeCancelOrDispose(ChannelWire.RequestType.PromiseCancel, 3)))
        assertEquals(
            expectedOf("eventfire"),
            hex(
                RpcSerialization.encodeAll(
                    listOf(
                        RpcValue.Arr(listOf(RpcValue.Int(204), RpcValue.Int(2))),
                        RpcValue.Obj(buildJsonObject {
                            put("topic", JsonPrimitive("conversation/s1"))
                            put("frame", buildJsonObject { put("kind", JsonPrimitive("complete")) })
                        }),
                    )
                )
            )
        )
        assertEquals(
            expectedOf("initialize"),
            hex(
                RpcSerialization.encodeAll(
                    listOf(
                        RpcValue.Arr(listOf(RpcValue.Int(200))),
                        RpcValue.Undefined,
                    )
                )
            )
        )
    }

    // ---------------------------------------------------------- codec fuzz + limits

    @Test
    fun `malformed input never escapes as anything but ProtocolException`() {
        val rnd = Random(42)
        repeat(2000) {
            val bytes = ByteArray(rnd.nextInt(1, 128)) { rnd.nextInt(0, 256).toByte() }
            try {
                RpcSerialization.decode(bytes)
            } catch (e: ProtocolException) {
                // expected typed failure
            } catch (e: Throwable) {
                throw AssertionError("untyped failure on ${hex(bytes)}", e)
            }
        }
    }

    @Test
    fun `crc mismatch on inbound rpc-frame raises ProtocolException (S11)`() {
        val payload = "x".repeat(1000).encodeToByteArray()
        val frags = RelayFrameCodec.fragment("bridge-1", null, null, payload, seq = 1, messageSeq = 1)
        val broken = frags[0].envelopeJson.replace(Regex("\"value\":\"[0-9a-f]{8}\""), "\"value\":\"00000000\"")
        val assembler = RelayFrameCodec.Assembler()
        assertFailsWith<ProtocolException> { assembler.handleEnvelope(broken) }
    }

    @Test
    fun `fragment round-trip at boundary sizes`() {
        for (size in listOf(1, 100, 700_000, 786_432 * 3 + 17)) {
            val payload = ByteArray(size) { (it % 251).toByte() }
            val frags = RelayFrameCodec.fragment("bridge-x", 0, "rec-1", payload, seq = 1, messageSeq = 9)
            val assembler = RelayFrameCodec.Assembler()
            var delivered: RelayFrameCodec.Reassembled.Message? = null
            for (f in frags) {
                assembler.handleEnvelope(f.envelopeJson)
                    .filterIsInstance<RelayFrameCodec.Reassembled.Message>()
                    .forEach { delivered = it }
            }
            assertContentEquals(payload, delivered?.payload, "round-trip size=$size")
            assertEquals(9L, delivered?.messageSeq)
        }
    }

    @Test
    fun `oversize logical message is refused before allocation (INV-5)`() {
        assertFailsWith<ProtocolException> {
            RelayFrameCodec.fragment("bridge-x", null, null, ByteArray(RelayLimits.RELAY_MAX_MESSAGE_BYTES + 1), 1, 1)
        }
    }

    @Test
    fun `duplicate inbound fragment is an idempotent drop and assembly still completes`() {
        val payload = ByteArray(1_500_000) { 7 }
        val frags = RelayFrameCodec.fragment("bridge-dup", null, null, payload, 1, 1)
        val assembler = RelayFrameCodec.Assembler()
        // duplicate the first fragment before the set completes
        assembler.handleEnvelope(frags[0].envelopeJson)
        assembler.handleEnvelope(frags[0].envelopeJson)
        var messages = 0
        for (f in frags.drop(1)) {
            messages += assembler.handleEnvelope(f.envelopeJson)
                .count { it is RelayFrameCodec.Reassembled.Message }
        }
        assertEquals(1, messages)
    }
}
