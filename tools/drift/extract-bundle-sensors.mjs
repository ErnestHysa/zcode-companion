#!/usr/bin/env node
// D3/H5/N10 shipped-bundle sensor extractor (gaps-and-polish Phase 2H).
//
//   node tools/drift/extract-bundle-sensors.mjs --asar /Applications/ZCode.app/Contents/Resources/app.asar \
//        --out tools/drift/bundle-sensors-baseline.json
//
// Extracts the asar (via @electron/asar through npx) into a temp dir, runs the
// facade/i18n/css sensors (bundle-lib.mjs), and writes the JSON payload. The output
// is a GENERATED baseline: regenerate against each desktop release, never hand-edit.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { extractBundleSensors } from "./bundle-lib.mjs";

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const asar = resolve(arg("asar") ?? "");
const out = arg("out");
if (!asar || !out) {
  console.error("usage: extract-bundle-sensors.mjs --asar <app.asar> --out <path>");
  process.exit(2);
}

const tmp = mkdtempSync(join(tmpdir(), "zcode-bundle-sensors-"));
try {
  execFileSync("npx", ["--yes", "@electron/asar", "extract", asar, tmp], { stdio: "inherit" });
  const sensors = extractBundleSensors(join(tmp, "out"));
  const version = JSON.parse(readFileSync(join(tmp, "package.json"), "utf8")).version ?? null;
  const payload = { _comment: "GENERATED by extract-bundle-sensors.mjs — regenerate, never hand-edit.", desktopVersion: version, ...sensors };
  writeFileSync(resolve(out), JSON.stringify(payload, null, 2) + "\n");
  console.log(`facade=${sensors.facade.length} i18nNamespaces=${Object.keys(sensors.i18nNamespaces).length} cssProps=${Object.keys(sensors.css).length} desktop=${version}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
