#!/usr/bin/env bash
# AAP-2 bundle sensor (android-gaps roadmap Phase 5) — the Mac-in-loop leg of
# the auto-adaptation T1 detect tier (report §14.2). INV-15 note: this sensor
# NEVER connects to the production relay; it hashes and text-scans local bundle
# files only.
#
# Tripwire: sha256(app.asar)/sha256(zcode.cjs) vs the committed baseline. On a
# hash change it re-extracts the Phase-1-corpus relay-adapter constants
# (close codes, QI adapter limits, envelope/rpc-frame fields, relay error codes),
# diffs them against tools/drift/relay-baseline.json, writes
# $DRIFT_STATE_DIR/drift-report.json and notifies (log + macOS notification).
# Unchanged bundles exit quietly after a heartbeat log line. The committed
# baseline is regenerated BY HAND after review (never auto-overwritten):
#   node tools/drift/extract-relay-surface.mjs --asar "$ASAR" --cjs "$CJS" \
#     --out tools/drift/relay-baseline.json
#
# Scheduled by launchd (docs/runbooks/drift.md); env overrides:
#   ZCODE_ASAR, ZCODE_CJS, DRIFT_STATE_DIR, DRIFT_RELAY_BASELINE,
#   DRIFT_NO_OSD=1 (log-only notifications, e.g. rehearsals/CI-like runs).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

ASAR="${ZCODE_ASAR:-/Applications/ZCode.app/Contents/Resources/app.asar}"
CJS="${ZCODE_CJS:-/Applications/ZCode.app/Contents/Resources/glm/zcode.cjs}"
STATE_DIR="${DRIFT_STATE_DIR:-$HOME/Library/Logs/zcode-android-drift}"
BASELINE="${DRIFT_RELAY_BASELINE:-$REPO_ROOT/tools/drift/relay-baseline.json}"

log() { printf '[%s] %s\n' "$(date '+%Y-%m-%dT%H:%M:%S%z')" "$*" >> "$STATE_DIR/sensor.log"; }

mkdir -p "$STATE_DIR"

if [[ ! -f "$ASAR" && ! -f "$CJS" ]]; then
  log "error: neither bundle file exists (asar=$ASAR cjs=$CJS)"
  exit 2
fi

app_hash="none"
[[ -f "$ASAR" ]] && app_hash="$(shasum -a 256 "$ASAR" | awk '{print $1}')"
cjs_hash="none"
[[ -f "$CJS" ]] && cjs_hash="$(shasum -a 256 "$CJS" | awk '{print $1}')"

read_base_hash() {
  node -e '
    const fs = require("fs");
    try {
      const b = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
      const key = process.argv[2];
      console.log(b.source?.[key] ?? "none");
    } catch { console.log("none"); }
  ' "$BASELINE" "$1"
}

base_app="$(read_base_hash appSha256)"
base_cjs="$(read_base_hash cjsSha256)"

if [[ "$app_hash" == "$base_app" && "$cjs_hash" == "$base_cjs" ]]; then
  log "heartbeat: bundle unchanged (asar=${app_hash:0:12} cjs=${cjs_hash:0:12})"
  exit 0
fi

log "tripwire: bundle hash changed (asar ${base_app:0:12} -> ${app_hash:0:12}, cjs ${base_cjs:0:12} -> ${cjs_hash:0:12}) — extracting relay surface"

extract_args=()
[[ -f "$ASAR" ]] && extract_args+=(--asar "$ASAR")
[[ -f "$CJS" ]] && extract_args+=(--cjs "$CJS")

set +e
node "$REPO_ROOT/tools/drift/extract-relay-surface.mjs" \
  ${extract_args[@]+"${extract_args[@]}"} \
  --out "$STATE_DIR/relay-current.json"
extract_rc=$?
set -e
if [[ $extract_rc -ne 0 ]]; then
  log "error: relay-surface extraction failed (rc=$extract_rc)"
  node "$REPO_ROOT/tools/sensors/notify.mjs" --title "ZCode bundle drift" \
    --message "Bundle changed but relay-surface extraction FAILED — inspect $STATE_DIR" \
    --log "$STATE_DIR/notifications.log" ${DRIFT_NO_OSD:+--no-osd}
  exit 2
fi

set +e
node "$REPO_ROOT/tools/drift/check-drift.mjs" --kind relay \
  --current "$STATE_DIR/relay-current.json" \
  --baseline "$BASELINE" \
  --out "$STATE_DIR/drift-report.json"
drift_rc=$?
set -e

report_verdict="$(node -e '
  const fs = require("fs");
  try { console.log(JSON.parse(fs.readFileSync(process.argv[1], "utf8")).verdict); }
  catch { console.log("UNKNOWN"); }
' "$STATE_DIR/drift-report.json")"

if [[ "$report_verdict" == "BREAKING" ]]; then
  msg="ZCode desktop updated — BREAKING relay drift detected. Review $STATE_DIR/drift-report.json before connecting."
else
  msg="ZCode desktop updated — relay surface unchanged/ADDITIVE ($report_verdict). Consider regenerating relay-baseline.json."
fi

node "$REPO_ROOT/tools/sensors/notify.mjs" --title "ZCode bundle drift" \
  --message "$msg" --log "$STATE_DIR/notifications.log" ${DRIFT_NO_OSD:+--no-osd}

log "drift checked: verdict=$report_verdict exit=$drift_rc report=$STATE_DIR/drift-report.json"
exit "$drift_rc"
